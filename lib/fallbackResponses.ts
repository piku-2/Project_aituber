// LLM（Gemini）が利用できないときに返す定型文集。
// レートリミット超過・ネットワーク切断・その他エラー時のフォールバックとして使う。
// 夜泊 聖華の口調・文化祭デモという文脈に合うよう、どんな問いかけにも
// 不自然にならない汎用的なセリフを並べている。

export const FALLBACK_RESPONSES: readonly string[] = [
  "ふふ、ごめんなさい。少し考えがまとまらないみたいです。もう一度話しかけてもらえますか？",
  "あら、いま少し電波の調子が悪いみたい。落ち着いたらまたお話ししましょうね。",
  "ごめんなさい、頭の中が混み合っているみたいなのです。もう一度ゆっくり聞かせてください。",
  "むむ、うまく言葉が出てこないわ。よかったら、もう一度話しかけてくださいな。",
  "ちょっと待っていてくださいね。今は少し調子が出ないみたいなのです。",
  "あらあら、今日はたくさんの方とお話ししていて、少し疲れてしまったみたい。もう一度どうぞ。",
  "ごめんなさい、いま考えがまとまらないの。文化祭、楽しんでいってくださいね。",
  "うーん、うまくお返事できなくてごめんなさい。もう少しだけ待ってもらえると嬉しいわ。",
] as const;

/** 定型文をランダムに1つ返す。 */
export function getRandomFallback(): string {
  const i = Math.floor(Math.random() * FALLBACK_RESPONSES.length);
  return FALLBACK_RESPONSES[i];
}
